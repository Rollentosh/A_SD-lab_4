from ultralytics import YOLO

def train_model():
    model = YOLO("yolov8s.pt")

    results = model.train(
        data="dataset/data.yaml",
        epochs=3,               # !!! число эпох (сколько раз модель пройдет по датасету)
                                # !!! < 50 не успеет обучиться, > 120 переобучится
        imgsz=640,              # стандартное разрешение картинок
        batch=8,                # размер партии картинок до обновления весов 
                                # (Вова может поставить 16 или 32 на крутой видюхе)
        patience=20,            # ранняя остановка, если метрики не растут 20 эпох
        freeze=10,              # заморозка слоев backbone (формы, цвета, тени углы)    - не трогать
        lr0=0.001,              # начальный шаг обучения (learning rate)                - не трогать
        hsv_h=0.015,            # аугментация оттенка (загуглите)                       - особо не крутить
        hsv_s=0.5,              # аугментация насыщенности
        hsv_v=0.4,              # аугментация яркости
        mosaic=1.0,             # помогает находить мелкие конусы вдалеке               - не трогать
        name="cones_yolov8s"
    )

if __name__ == "__main__":
    train_model()
